#!/usr/bin/env node
// Generates src/api/contract.gen.ts from backend/quantfolio/contracts.py.
//
// The backend's pydantic models are the single source of truth. This script
// asks the backend venv to dump their JSON Schemas (scripts/dump_contract_schema.py)
// and converts them to TypeScript:
//   - `X`       response shape (serialisation mode; every property is present)
//   - `XInput`  request shape  (validation mode; defaulted properties optional)
//   - literal unions + `as const` arrays, field bounds/defaults for form validation.
//
// Usage: npm run gen:types          (writes the file)
//        npm run check:types        (fails if the committed file is stale)

import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const frontend = resolve(here, '..')
const root = resolve(frontend, '..')
const outFile = join(frontend, 'src', 'api', 'contract.gen.ts')
const python = process.env.QF_PYTHON ?? join(root, 'backend', '.venv', process.platform === 'win32' ? 'Scripts/python.exe' : 'bin/python')
const checkOnly = process.argv.includes('--check')

if (!existsSync(python)) {
  console.error(`Backend Python not found at ${python}. Set QF_PYTHON or run scripts\\setup.ps1.`)
  process.exit(2)
}

const raw = execFileSync(python, [join(here, 'dump_contract_schema.py')], { encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 })
const dump = JSON.parse(raw)

const lines = []
const push = (s = '') => lines.push(s)

push('// AUTO-GENERATED by scripts/gen-contract-types.mjs from backend/quantfolio/contracts.py.')
push('// Do not edit by hand. Regenerate with `npm run gen:types`.')
push('/* eslint-disable */')
push('')
push(`export const SCHEMA_VERSION = ${JSON.stringify(dump.constants.SCHEMA_VERSION)} as const`)
push(`export const DISCLAIMER = ${JSON.stringify(dump.constants.DISCLAIMER)}`)
push('')

// Literal aliases -------------------------------------------------------------
const literalByKey = new Map()
for (const [name, values] of Object.entries(dump.literals).sort()) {
  const constName = name.replace(/([a-z])([A-Z])/g, '$1_$2').toUpperCase() + '_VALUES'
  push(`export const ${constName} = ${JSON.stringify(values)} as const`)
  push(`export type ${name} = (typeof ${constName})[number]`)
  literalByKey.set(JSON.stringify([...values].sort()), name)
}
push('')

const tsKey = (k) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k))

function typeOf(schema, suffix) {
  if (!schema || Object.keys(schema).length === 0) return 'unknown'
  if (schema.$ref) return schema.$ref.split('/').pop() + suffix
  if (schema.enum) {
    const named = literalByKey.get(JSON.stringify([...schema.enum].sort()))
    return named ?? schema.enum.map((v) => JSON.stringify(v)).join(' | ')
  }
  if ('const' in schema) return JSON.stringify(schema.const)
  if (schema.anyOf || schema.oneOf) {
    const parts = (schema.anyOf ?? schema.oneOf).map((s) => typeOf(s, suffix))
    return [...new Set(parts)].join(' | ')
  }
  switch (schema.type) {
    case 'string':
      return 'string'
    case 'integer':
    case 'number':
      return 'number'
    case 'boolean':
      return 'boolean'
    case 'null':
      return 'null'
    case 'array':
      return `Array<${typeOf(schema.items, suffix)}>`
    case 'object': {
      if (schema.properties) return inlineObject(schema, suffix, true)
      const ap = schema.additionalProperties
      return `Record<string, ${ap && ap !== true ? typeOf(ap, suffix) : 'unknown'}>`
    }
    default:
      return 'unknown'
  }
}

function inlineObject(schema, suffix, allRequired) {
  const req = new Set(schema.required ?? [])
  const props = Object.entries(schema.properties ?? {}).map(([k, v]) => {
    const opt = allRequired ? '' : req.has(k) ? '' : '?'
    return `${tsKey(k)}${opt}: ${typeOf(v, suffix)}`
  })
  return `{ ${props.join('; ')} }`
}

function emitModels(defs, suffix, allRequired) {
  for (const [name, schema] of Object.entries(defs).sort()) {
    const req = new Set(schema.required ?? [])
    if (schema.description) push(`/** ${schema.description.replace(/\*\//g, '* /').replace(/\n+/g, ' ')} */`)
    push(`export interface ${name}${suffix} {`)
    for (const [k, v] of Object.entries(schema.properties ?? {})) {
      const optional = allRequired ? false : !req.has(k)
      const doc = v.description ? `  /** ${v.description.replace(/\*\//g, '* /')} */\n` : ''
      lines.push(`${doc}  ${tsKey(k)}${optional ? '?' : ''}: ${typeOf(v, suffix)}`)
    }
    push('}')
    push('')
  }
}

push('// ---- Response shapes (server always sends every property) -------------------')
emitModels(dump.serialization, '', true)
push('// ---- Request shapes (properties with server defaults are optional) ----------')
emitModels(dump.validation, 'Input', false)

// Bounds/defaults for client-side validation ----------------------------------
const bounds = {}
for (const [name, schema] of Object.entries(dump.validation).sort()) {
  const fields = {}
  for (const [k, v] of Object.entries(schema.properties ?? {})) {
    const base = v.anyOf ? v.anyOf.find((s) => s.type === 'number' || s.type === 'integer') ?? v : v
    const b = {}
    for (const key of ['minimum', 'maximum', 'exclusiveMinimum', 'exclusiveMaximum', 'minLength', 'maxLength', 'minItems', 'maxItems']) {
      if (base[key] !== undefined) b[key] = base[key]
      if (v[key] !== undefined) b[key] = v[key]
    }
    if (base.type === 'integer') b.integer = true
    if (v.default !== undefined && v.default !== null && typeof v.default !== 'object') b.default = v.default
    if (Object.keys(b).length) fields[k] = b
  }
  if (Object.keys(fields).length) bounds[name] = fields
}
push('export interface FieldBounds { minimum?: number; maximum?: number; exclusiveMinimum?: number; exclusiveMaximum?: number; minLength?: number; maxLength?: number; minItems?: number; maxItems?: number; integer?: boolean; default?: string | number | boolean }')
push(`export const BOUNDS = ${JSON.stringify(bounds, null, 2)} as const satisfies Record<string, Record<string, FieldBounds>>`)
push('')

const text = lines.join('\n')
if (checkOnly) {
  const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : ''
  if (current.replace(/\r\n/g, '\n') !== text) {
    console.error('src/api/contract.gen.ts is stale: run `npm run gen:types`.')
    process.exit(1)
  }
  console.log('contract.gen.ts matches backend/quantfolio/contracts.py')
} else {
  writeFileSync(outFile, text)
  console.log(`wrote ${outFile} (${lines.length} lines)`)
}
